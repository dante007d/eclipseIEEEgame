/**
 * Pick an unseen entry from `pool` tracked on `tracker` ({ seen: Set<string>, last?: string | null }).
 * Automatically resets only after all entries in `pool` are exhausted, never repeating `tracker.last` back-to-back.
 */
export function pickUnique(pool, tracker) {
  if (!Array.isArray(pool) || pool.length === 0) return '';
  if (!tracker) {
    return pool[Math.floor(Math.random() * pool.length)];
  }
  if (!(tracker.seen instanceof Set)) {
    tracker.seen = new Set(Array.isArray(tracker.seen) ? tracker.seen : []);
  }
  let remaining = pool.filter((item) => !tracker.seen.has(item));
  if (remaining.length === 0) {
    tracker.seen.clear();
    remaining = pool.length > 1 ? pool.filter((item) => item !== tracker.last) : pool;
  }
  const chosen = remaining[Math.floor(Math.random() * remaining.length)];
  tracker.seen.add(chosen);
  tracker.last = chosen;
  return chosen;
}

/**
 * Use `candidate` if provided and not yet seen in `tracker`; otherwise pull a guaranteed fresh entry from `pool`.
 */
export function claimUnique(candidate, pool, tracker) {
  if (!tracker) {
    return candidate || (Array.isArray(pool) && pool.length > 0 ? pool[0] : '');
  }
  if (!(tracker.seen instanceof Set)) {
    tracker.seen = new Set(Array.isArray(tracker.seen) ? tracker.seen : []);
  }
  if (candidate && !tracker.seen.has(candidate) && candidate !== tracker.last) {
    tracker.seen.add(candidate);
    tracker.last = candidate;
    return candidate;
  }
  return pickUnique(pool, tracker);
}

